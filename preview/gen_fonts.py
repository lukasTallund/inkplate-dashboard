"""Turn the `font:` section of dashboard.yaml into fonts.inc for the preview.

Reads font ids, files, sizes and glyph lists, plus the order the display
lambda passes them to dash::Fonts, so the preview never drifts from the YAML.
Font files come from ESPHome's cache in .esphome/font, which exists after one
`esphome compile dashboard.yaml`.

Usage: python gen_fonts.py <dashboard.yaml> <.esphome/font dir> <out.inc>
"""

import glob
import os
import re
import sys

import yaml


class Loader(yaml.SafeLoader):
    pass


# !secret and friends: keep the tag's value, it doesn't matter here.
Loader.add_multi_constructor("!", lambda loader, suffix, node: None)


def font_path(file, cache):
    if file["type"] == "gfonts":
        weight = file.get("weight", 400)
        italic = file.get("italic", False)
        return os.path.join(cache, f"{file['family']}@{weight}@{italic}@v1.ttf")
    # type: web — ESPHome stores it as <hash>/font.ttf. There is only one here.
    found = glob.glob(os.path.join(cache, "*", "font.ttf"))
    if len(found) != 1:
        sys.exit(f"expected exactly one web font in {cache}, found {found}")
    return found[0]


def c_string(s):
    return '"' + "".join(f"\\x{b:02x}" for b in s.encode("utf-8")) + '"'


def main():
    yaml_path, cache, out = sys.argv[1:4]
    with open(yaml_path, encoding="utf-8") as fh:
        text = fh.read()
    config = yaml.load(text, Loader=Loader)

    lines = []
    for font in config["font"]:
        path = font_path(font["file"], cache)
        if not os.path.exists(path):
            sys.exit(f"{path} missing; run `esphome compile dashboard.yaml` once")
        glyphs = font.get("glyphs", "")
        if isinstance(glyphs, list):
            glyphs = "".join(glyphs)
        # Glyphsets mean "everything we'd use"; leave the glyph list empty.
        if font.get("glyphsets"):
            glyphs = ""
        lines.append(f'  {{"{font["id"]}", "{os.path.abspath(path)}", {font["size"]}, {c_string(glyphs)}}},')

    order = re.search(r"dash::Fonts f\{(.*?)\};", text, re.S)
    if not order:
        sys.exit("could not find `dash::Fonts f{...};` in the display lambda")
    ids = re.findall(r"id\((\w+)\)", order.group(1))

    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by gen_fonts.py from dashboard.yaml. Do not edit.\n")
        fh.write("static const FontSpec FONT_SPECS[] = {\n" + "\n".join(lines) + "\n};\n")
        fh.write("static const char *FONT_ORDER[] = {" + ", ".join(f'"{i}"' for i in ids) + "};\n")


main()
